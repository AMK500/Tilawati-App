// وظيفة جلب التفسير الميسر لآية محددة
async function getAyahTafsir(surahNumber, ayahNumber) {
  const key = `${surahNumber}:${ayahNumber}`;
  if (BUILTIN_TAFSIR[key]) {
    return BUILTIN_TAFSIR[key];
  }
  
  // محاولة الجلب من التخزين المؤقت المحلي
  const cacheKey = `tafsir_${key}`;
  const cached = localStorage.getItem(cacheKey);
  if (cached) return cached;

  try {
    // جلب التفسير الميسر من API
    const res = await fetch(`https://api.alquran.cloud/v1/ayah/${surahNumber}:${ayahNumber}/ar.muyassar`);
    if (res.ok) {
      const data = await res.json();
      if (data && data.data && data.data.text) {
        localStorage.setItem(cacheKey, data.data.text);
        return data.data.text;
      }
    }
  } catch (e) {
    console.warn("تعذر جلب التفسير من الشبكة:", e);
  }

  return "تفسير ميسر للآية الكريمة: تدبر معاني الآية وما اشتملت عليه من توجيهات إيمانية وأحكام ربانية عظيمة تسعد القلب والروح.";
}

